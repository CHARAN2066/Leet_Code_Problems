class Solution {
public:
    long long countCommas(long long n) {
        long long int ans=0;
        if(n<1000)
            return 0;
        if(n<=999999){
            return (n-1000+1);
        }
        if(n<=999999999){
            return (999999-1000+1)+(n-1e6+1)*2;
        }
        if(n<=(999999999999)){
            return (999999-1000+1)+(999999999-1e6+1)*2+(n-1e9+1)*3;
        }
        if(n<=(999999999999999)){
            return (999999-1000+1)+(999999999-1e6+1)*2+(999999999999-1e9+1)*3+(n-1e12+1)*4;
        }
        else{
            return (999999-1000+1)+(999999999-1e6+1)*2+(999999999999-1e9+1)*3+(999999999999999-1e12+1)*4+5;
        }
        return -1;
    }
};